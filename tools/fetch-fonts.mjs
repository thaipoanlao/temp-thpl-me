#!/usr/bin/env node
/**
 * fetch-fonts.mjs — downloads the Noto Sans Thai / Noto Sans Lao webfonts
 * used by this site and writes `fonts.css` with local relative URLs.
 *
 * Works in both places:
 *   - locally:  node tools/fetch-fonts.mjs . assets
 *   - Cloudflare Pages build: called by tools/build.mjs into dist/assets
 *
 * If the network is unavailable it writes a safe fallback fonts.css and exits 0,
 * so a build never breaks because of fonts.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const siteDir = process.argv[2] || '.';
const outDir = path.join(siteDir, process.argv[3] || 'assets');
const fontDir = path.join(outDir, 'fonts');

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Noto+Sans+Thai:wght@400;500;600&family=Noto+Sans+Lao:wght@400;600&display=swap';
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const WANTED = {
  'Noto Sans Thai': ['400', '500', '600'],
  'Noto Sans Lao': ['400', '600'],
};

async function fetchWithRetry(url, tries = 3) {
  let lastErr;
  for (let i = 0; i < tries; i++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': UA } });
      if (!res.ok) throw new Error('HTTP ' + res.status);
      return res;
    } catch (e) {
      lastErr = e;
      if (i < tries - 1) await new Promise((r) => setTimeout(r, 900 * (i + 1)));
    }
  }
  throw lastErr;
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-');

async function main() {
  await mkdir(fontDir, { recursive: true });

  let css = '';
  try {
    css = await (await fetchWithRetry(CSS_URL)).text();
  } catch (e) {
    console.warn('[fonts] could not fetch Google Fonts CSS:', e.message);
    console.warn('[fonts] writing fallback fonts.css (system fonts will be used)');
    await writeFile(path.join(outDir, 'fonts.css'), '/* webfonts unavailable during build - system font fallback */\n', 'utf8');
    return;
  }

  // Collect @font-face blocks (family / weight / url / unicode-range)
  const faces = [];
  for (const m of css.matchAll(/@font-face\s*\{([^}]+)\}/g)) {
    const body = m[1];
    const pick = (re) => { const r = body.match(re); return r ? r[1].trim() : null; };
    const family = pick(/font-family:\s*'([^']+)'/);
    const weight = pick(/font-weight:\s*(\d+)/);
    const url = pick(/url\((https:\/\/[^)]+?\.woff2)\)/);
    const range = pick(/unicode-range:\s*([^;]+);/);
    if (family && weight && url) faces.push({ family, weight, url, range });
  }

  const wanted = faces.filter((f) => WANTED[f.family] && WANTED[f.family].includes(f.weight));
  if (!wanted.length) {
    console.warn('[fonts] no matching @font-face blocks found - writing fallback');
    await writeFile(path.join(outDir, 'fonts.css'), '/* webfonts unavailable during build - system font fallback */\n', 'utf8');
    return;
  }

  // Google may serve the same variable-font file for several weights — download each unique URL
  // once and point every @font-face block at the shared file.
  const urlMap = new Map();
  const countByFamily = new Map();
  const rules = [];
  let ok = 0, skipped = 0, bytes = 0;

  for (const f of wanted) {
    let file = urlMap.get(f.url);
    if (file === undefined) {
      const fam = slug(f.family);
      const idx = (countByFamily.get(fam) || 0) + 1;
      countByFamily.set(fam, idx);
      file = `${fam}-${idx}.woff2`;
      try {
        const buf = Buffer.from(await (await fetchWithRetry(f.url)).arrayBuffer());
        await writeFile(path.join(fontDir, file), buf);
        bytes += buf.length;
        ok++;
      } catch (e) {
        skipped++;
        file = null;
        console.warn(`[fonts] failed: ${f.family} ${f.weight} ${f.url.slice(0, 60)}… — ${e.message}`);
      }
      urlMap.set(f.url, file);
    }
    if (!file) continue;
    rules.push(
      `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${f.weight};font-display:swap;` +
        `src:url('fonts/${file}') format('woff2');` +
        (f.range ? `unicode-range:${f.range};` : '') +
        '}'
    );
  }

  await writeFile(
    path.join(outDir, 'fonts.css'),
    '/* Generated by tools/fetch-fonts.mjs — do not edit by hand */\n' + rules.join('\n') + '\n',
    'utf8'
  );
  console.log(`[fonts] wrote ${ok} unique font files (${(bytes / 1024).toFixed(1)} KB), ${rules.length} @font-face rules, skipped ${skipped} → ${path.join(outDir, 'fonts.css')}`);
}

main().catch((e) => {
  console.warn('[fonts] unexpected error:', e.message);
  process.exitCode = 0; // never break the build because of fonts
});
